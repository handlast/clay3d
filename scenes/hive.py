from clay_proto import prim, group

WALL = (250, 232, 196); CELL = (240, 184, 92); CELL_L = (255, 222, 150); FLOOR = (168, 112, 70)

def hive(t=0.0, extra=(), wall=WALL, floor=FLOOR, zw=-2.4, cells=True):
    for j, cx in enumerate((-2.6, 0.0, 2.6)):
        g = group((cx, 2.0, zw), 2.7)
        prim(2, 0, [cx, 2.0, zw], [1.3, 2.6, 0.2], 0.04, 0, wall, 0.12, g)
        if cells:
            for r in range(5):
                for c in range(3):
                    hx = cx - 0.86 + c * 0.86 + (0.43 if r % 2 else 0.0)
                    if abs(hx - cx) > 1.18: continue
                    hy = 0.55 + r * 0.74
                    prim(0, 2, [hx, hy, zw + 0.2], [0.36, 0.33, 0.06], 0.004, 0.03, CELL, 0.15, g)
                    prim(0, 2, [hx - 0.08, hy + 0.08, zw + 0.2], [0.16, 0.13, 0.065], 0.003, 0.05, CELL_L, 0.2, g)
    gf = group((0, -0.1, 0), 5.0)
    prim(2, 0, [0, -0.1, 0], [4.2, 0.1, 3.4], 0.05, 0, floor, 0.12, gf)
    if "moon" in extra:      # 圆窗：深蓝夜空 + 月亮 + 两颗星（涂在墙上）
        g = group((0.95, 2.35, zw + 0.25), 0.7)
        prim(0, 0, [0.95, 2.35, zw + 0.12], [0.62, 0.62, 0.16], 0, 0.03, (190, 130, 50), 0.2, g)
        prim(0, 1, [0.95, 2.35, zw + 0.3], [0.5, 0.5, 0.1], 0, 0.02, (40, 60, 120), 0.2, g)
        prim(0, 0, [1.08, 2.47, zw + 0.2], [0.14, 0.14, 0.05], 0, 0.0, (255, 246, 200), 0.6, g)
        for (sx, sy_) in ((0.75, 2.6), (0.8, 2.15)):
            prim(0, 0, [sx, sy_, zw + 0.2], [0.03, 0.03, 0.02], 0, 0.0, (255, 250, 220), 0.6, g)
    if "door" in extra:      # 出口：墙上大圆洞，洞里是蓝天 + 绿地（像窗外）
        g = group((-0.9, 1.3, zw + 0.25), 1.0)
        prim(0, 0, [-0.9, 1.3, zw + 0.12], [0.86, 0.86, 0.16], 0, 0.03, (196, 136, 52), 0.2, g)
        prim(0, 1, [-0.9, 1.3, zw + 0.3], [0.72, 0.72, 0.1], 0, 0.02, (150, 210, 250), 0.2, g)
        prim(0, 2, [-0.9, 0.82, zw + 0.24], [0.66, 0.2, 0.08], 0.003, 0.03, (120, 196, 96), 0.2, g)
        prim(0, 2, [-1.15, 1.6, zw + 0.24], [0.16, 0.07, 0.08], 0.003, 0.02, (255, 255, 255), 0.2, g)
    if "board" in extra:     # 公告板：一块浅色板 + 两张便签
        g = group((-1.05, 2.25, zw + 0.25), 0.8)
        prim(2, 0, [-1.05, 2.25, zw + 0.24], [0.62, 0.42, 0.04], 0.03, 0.0, (250, 240, 214), 0.2, g)
        prim(2, 2, [-1.25, 2.35, zw + 0.29], [0.16, 0.13, 0.02], 0.0, 0.006, (255, 140, 140), 0.2, g)
        prim(2, 2, [-0.85, 2.15, zw + 0.29], [0.16, 0.13, 0.02], 0.0, 0.006, (140, 210, 255), 0.2, g)

def meadow(t=0.0, sky=(150, 206, 246), grass=(132, 196, 96), hole=(0.0, 0.0)):
    g = group((0, 2.2, -3.0), 5.4)
    prim(2, 0, [0, 2.2, -3.0], [5.0, 3.4, 0.2], 0.04, 0, sky, 0.1, g)
    prim(0, 2, [-1.6, 0.4, -2.8], [1.8, 0.9, 0.1], 0.003, 0.05, (120, 176, 120), 0.1, g)      # 远山
    prim(0, 2, [1.5, 0.3, -2.8], [2.0, 0.8, 0.1], 0.003, 0.05, (100, 160, 110), 0.1, g)
    prim(0, 2, [1.2, 3.1, -2.8], [0.3, 0.3, 0.1], 0.003, 0.02, (255, 236, 150), 0.3, g)        # 太阳
    for (cx, cy) in ((-1.3, 3.2), (-0.9, 3.25)):
        prim(0, 2, [cx, cy, -2.8], [0.3, 0.14, 0.1], 0.003, 0.03, (255, 255, 255), 0.1, g)
    gf = group((0, -0.1, 0), 5.0)
    prim(2, 0, [0, -0.1, 0], [4.5, 0.1, 3.6], 0.05, 0, grass, 0.1, gf)
    hx, hz = hole
    prim(0, 1, [hx, 0.0, hz], [0.32, 0.12, 0.24], 0, 0.04, (70, 50, 40), 0.1, gf)              # 地洞
    prim(0, 2, [hx, -0.02, hz], [0.5, 0.06, 0.38], 0.004, 0.08, (150, 120, 80), 0.1, gf)      # 洞口一圈土
    return {"hole": [hx, 0.0, hz]}
