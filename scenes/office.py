if __name__ == "__main__":
    PI, PF, GR, G0, G1 = build()
    flags = np.array([1, 1, 1, 1, 1, 1, 1], np.int64)
    CAM = np.array([0.0, 1.15, 4.4]); TGT = np.array([0.0, 0.9, 0.0])
    L = np.array([-0.55, 0.75, 0.55]); L /= np.linalg.norm(L)
    w, h = 720, 1280
    img = np.zeros((h, w, 3)); dep = np.zeros((h, w))
    t0 = time.time()
    cp.render(w, h, 0, w, 0, h, CAM, TGT, math.radians(44), L, PI, PF, GR, G0, G1, img, dep, flags, 0.0)
    print("render", round(time.time() - t0, 2))
    focus = float(np.linalg.norm(CAM - np.array([0, 0.8, 0.1])))
    out = cp.post(img, dep, focus)
    cv2.imwrite("office_G.png", out[..., ::-1])
